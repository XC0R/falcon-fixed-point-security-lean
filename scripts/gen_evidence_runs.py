HEXF = r"([+-]0x[0-9A-Fa-f.]+p[+-]\d+)\s+\(([^)]*)\)"
NCALL = 128   # SamplerZ calls per run file
NDEF = 16   # SamplerZ calls per list literal
TPATS = [
    ("mu", r"mu\s+= " + HEXF + "$"), ("isig", r"1/sigma = " + HEXF + "$"), ("s", r"s\s+= (-?\d+)$"),
    ("u", r"BaseSampler: u = 0x([0-9A-F]+) -> z0 = (\d+)$"),
    ("b", r"b\s+= ([01])  \(from random byte: 0x([0-9A-F]{2})\)$"), ("z", r"z\s+= (-?\d+)$"),
    ("za", r"z\s+= 0x([0-9A-F]{16}) \(-?\d+\)$"),
    ("ber", r"i = (\d+) -> w = (-?\d+)  \(from random byte: 0x([0-9A-F]{2})\)$"),
    ("ret", r"ret: ([01])$"), ("acc", r"Accepted, ret = (-?\d+)$")]


def hexfloat(h, dec):
    v = float.fromhex(h)
    assert abs(v - float(dec)) <= 1e-15 * max(1.0, abs(v)), (h, dec)
    return fractions.Fraction(v)


def parse_trace(text):
    """The SamplerZ calls of the trace: mu, 1/sigma, s, the rounds and the accepted value."""
    calls, cur, rnd = [], None, None
    for line in text.splitlines():
        t = line.strip()
        if t == "SamplerZ:":
            cur = {"rounds": []}
            calls.append(cur)
            continue
        if cur is None or "acc" in cur:
            continue
        for k, pat in TPATS:
            m = re.match(pat, t)
            if not m:
                continue
            g = m.groups()
            if k in ("mu", "isig"):
                cur[k] = hexfloat(*g)
            elif k == "s":
                if not cur["rounds"]:
                    cur["s"] = int(g[0])
            elif k == "u":
                rnd = {"u": int(g[0], 16), "z0": int(g[1]), "ber": []}
                cur["rounds"].append(rnd)
            elif k == "b":
                rnd["b"], rnd["c"] = int(g[0]), int(g[1], 16)
            elif k == "z":
                rnd["z"] = int(g[0])
            elif k == "za":
                rnd["za"] = int(g[0], 16)
            elif k == "ber":
                rnd["ber"].append((int(g[0]), int(g[1]), int(g[2], 16)))
            elif k == "ret":
                rnd["ret"] = int(g[0])
            else:
                cur["acc"] = int(g[0])
            break
    return calls


def check_trace(calls):
    """The trace's lines against each other: s = floor(mu); z0 from u (spec Table 3.1); b and z
    from the sign byte; each BerExp byte against z; the return values; accepted = s + z."""
    for k, c in enumerate(calls):
        assert c["s"] == c["mu"].numerator // c["mu"].denominator, k
        for j, r in enumerate(c["rounds"]):
            assert r["u"] < 2 ** 72 and sum(r["u"] < x for x in RCDT72) == r["z0"], (k, j)
            assert r["b"] == r["c"] & 1 and r["z"] == r["b"] + (2 * r["b"] - 1) * r["z0"], (k, j)
            for n, (i, w, u) in enumerate(r["ber"]):
                assert i == 56 - 8 * n and w == u - (r["za"] >> i) % 256, (k, j, n)
                assert (w == 0) == (n + 1 < len(r["ber"])), (k, j, n)
            assert r["ret"] == (1 if r["ber"][-1][1] < 0 else 0), (k, j)
            assert (r["ret"] == 1) == (j + 1 == len(c["rounds"])), (k, j)
        assert c["acc"] == c["s"] + c["rounds"][-1]["z"], k


def qlit(q):
    d = q.denominator.bit_length() - 1
    assert q.denominator == 2 ** d
    return "%d / 2 ^ %d" % (q.numerator, d) if d else "%d" % q.numerator


def call_lines(c):
    bs = "".join("%018x%02x" % (r["u"], r["c"]) + "".join("%02x" % u for _, _, u in r["ber"])
                 for r in c["rounds"])
    ch = chunks(bs, W)
    out = ["  (%s," % qlit(c["mu"]), "    %s," % qlit(c["isig"]), "    String.join ["]
    out += ['      "%s"%s' % (x, "]," if j + 1 == len(ch) else ",") for j, x in enumerate(ch)]
    out.append("    %d)" % c["acc"])
    return out


def main_trace(data, outdir):
    calls = parse_trace(data.decode("ascii"))
    assert len(calls) == 2048
    check_trace(calls)
    head = read_template("sampler-1024", "RunHead.lean")
    for j in range(len(calls) // NCALL):
        lo = NCALL * j
        lines = ["import FalconPrecision.Exec.SamplerZ", "",
                 "-- generated by scripts/gen_evidence_runs.py from "
                 "test-vector-sampler-falcon1024.txt",
                 "-- sha256 " + SHATRACE, "-- SamplerZ calls %d-%d" % (lo, lo + NCALL - 1), "",
                 head]
        for q in range(NCALL // NDEF):   # one list literal of 128 calls is too slow to elaborate
            lines.append("def calls%d : List Call := [" % q)
            for k, c in enumerate(calls[lo + NDEF * q:lo + NDEF * (q + 1)]):
                cl = call_lines(c)
                cl[-1] += "]" if k + 1 == NDEF else ","
                lines += cl
            lines.append("")
        lines += ["def calls : List Call :=", "  " + " ++ ".join(
            "calls%d" % q for q in range(NCALL // NDEF)), "", "#eval runCalls %d calls" % lo, ""]
        text = "\n".join(lines)
        assert all(len(x) <= 100 for x in text.split("\n"))
        write(outdir, "sampler-1024/calls-%d.lean" % j, text)


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    rsp, outdir = sys.argv[1], sys.argv[2]
    with open(rsp, "rb") as f:
        data = f.read()
    got = hashlib.sha256(data).hexdigest()
    if got == SHATRACE:
        main_trace(data, outdir)
        return
    if got == SHA1024:
        main1024(data, outdir)
        return
    if got != SHA:
        sys.exit("sha256 mismatch: got %s, expected %s, %s or %s"
                 % (got, SHA, SHA1024, SHATRACE))
    kd = katdata(data, got)
    imp = ["FalconPrecision.Exec.Round3Codec", "FalconPrecision.Exec.CheckFast"]
    h45 = read_template("key-check-d45", "RunHead.lean")
    h127 = read_template("key-check-d127", "RunHead.lean")
    for rm in ("halfEven", "halfUp"):
        for half, lo, hi in (("a", 0, 50), ("b", 50, 100)):
            write(outdir, "key-check-d45/%s-0-%s.lean" % (rm, half),
                  key_run(imp + ["FalconPrecision.Exec.Instance45"], kd, h45,
                          "#eval runCfg .%s 0 %d %d" % (rm, lo, hi)))
            for xn in (0, 16, 32):
                write(outdir, "key-check-d127/%s-%d-%s.lean" % (rm, xn, half),
                      key_run(imp, kd, h127, "#eval runCfg .%s %d %d %d" % (rm, xn, lo, hi)))
    write(outdir, "key-check-d127/decode.lean", key_run(imp, kd, h127, "#eval runDecode 0 100"))
    write(outdir, "key-check-d127-xn32/survey.lean",
          "".join("import " + m + "\n" for m in imp) + "\n" + SURVEY_DOC + "\n" + kd + "\n"
          + read_template("key-check-d127-xn32", "RunTail.lean"))
    ents = parse(data.decode("ascii"))   # the checked bytes, not a second read
    assert [int(e["count"]) for e in ents] == list(range(100))
    for rel, text in kat_slices(ents):
        write(outdir, rel, text)
    for n in (0, 70, 27):
        write(outdir, "vectors/d45/e%d.lean" % n, vec_file(ents[n], n, False))
    for n in (0, 70):
        write(outdir, "vectors/d127/e%d.lean" % n, vec_file(ents[n], n, True))


main()
