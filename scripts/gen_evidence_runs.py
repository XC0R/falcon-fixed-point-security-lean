"""Write the run files of the KAT-dependent `#eval` evidence (Python 3, standard library only).

usage: python3 scripts/gen_evidence_runs.py <falcon512-KAT.rsp | falcon1024-KAT.rsp |
                                            test-vector-sampler-falcon1024.txt> <outdir>

The argument is the Falcon-512 or the Falcon-1024 KAT file, or the Falcon-1024 SamplerZ trace, of
the Falcon round-3 submission package (see evidence/README.md for where to download them); its
sha256 is checked first and decides which files are written. Every file written to <outdir> is
a Lean file run with `lake env lean <file>` from the repository root after `lake build`. From
falcon512-KAT.rsp:

  key-check-d45/{halfEven,halfUp}-0-{a,b}.lean            LIMITS E1
  key-check-d127/{halfEven,halfUp}-{0,16,32}-{a,b}.lean   LIMITS E2
  key-check-d127/decode.lean                              LIMITS E2
  key-check-d127-xn32/survey.lean                         LIMITS E3
  kat-entries/KatS0.lean ... KatS11.lean                  LIMITS E8
  vectors/d45/{e0,e70,e27}.lean, vectors/d127/{e0,e70}.lean  LIMITS E17

From falcon1024-KAT.rsp:

  kat1024-entries/KatS0.lean ... KatS<k>.lean             LIMITS E20
  kat1024-entries/HashToPoint.lean                        LIMITS E21
  key-check-1024-d43/{halfEven,halfUp}-0-<j>.lean         Falcon-1024 key check, δ43q_1024
  key-check-1024-d127/{halfEven,halfUp}-32-<j>.lean       Falcon-1024 key check, δ127q_1024
  key-check-1024-d127/decode.lean                         Falcon-1024 decode, ntruB, pkMatchB
  range-1024/{scaleFirst,multiplyFirst}-<j>.lean          Falcon-1024 integer ranges (checkRangeA)
    (<j> = 0 ... 9: keys 10j ... 10j + 9)
  vectors-1024/{d43,d127}/{e0,e2,e11}.lean                LIMITS E33

From test-vector-sampler-falcon1024.txt:

  sampler-1024/calls-<j>.lean                             SamplerZ at Falcon-1024 on the trace
    (<j> = 0 ... 15: SamplerZ calls 128j ... 128j + 127)

Each file is the KAT data (hexadecimal strings copied from the .rsp) followed by code from
evidence/ or from this script; a trace file is evidence/sampler-1024/RunHead.lean followed by
the trace's values (`mu` and `1/sigma` as the exact rationals of their binary64 values, the random
bytes in hexadecimal, the accepted `z`), after the trace's own lines are checked against each
other (`check_trace`). Nothing is read from the network.
"""
