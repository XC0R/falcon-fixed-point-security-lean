def write(outdir, rel, text):
    path = os.path.join(outdir, rel)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print(rel)


# ---- key data (E1, E2, E3): `katSk`, `katPk` for all entries

def chunks(s, w):
    return [s[i:i + w] for i in range(0, len(s), w)]


def lean_str(h):
    return "String.join [\n" + ",\n".join('    "' + p + '"' for p in chunks(h, 90)) + "]"


def katdata(data, sha, src="falcon512-KAT.rsp", perkey=False):
    ents, cur = [], {}
    for line in data.decode("ascii").splitlines():
        if " = " not in line:
            continue
        k, v = line.split(" = ", 1)
        if k == "count":
            cur = {"count": int(v)}
            ents.append(cur)
        elif k in ("sk", "pk"):
            if not all(c in "0123456789ABCDEFabcdef" for c in v):
                sys.exit("non-hex field")
            cur[k] = v
    if [e["count"] for e in ents] != list(range(len(ents))):
        sys.exit("count sequence")
    lines = ["-- generated by scripts/gen_evidence_runs.py from " + src,
             "-- sha256 " + sha, "-- entries: " + str(len(ents))]
    for name in ("sk", "pk"):
        nm = "kat" + name.capitalize()
        if perkey:   # one definition per key (one array literal of all keys is too deep to compile)
            for e in ents:
                lines.append("def %s%d : String := %s" % (nm, e["count"], lean_str(e[name])))
            lines.append("def %s : Array String := #[%s]"
                         % (nm, ", ".join(nm + str(e["count"]) for e in ents)))
            continue
        lines.append("def " + nm + " : Array String := #[")
        lines.append(",\n".join("  " + lean_str(e[name]) for e in ents))
        lines.append("]")
    return "\n".join(lines) + "\n"


def key_run(imports, kd, head, line):
    return "".join("import " + m + "\n" for m in imports) + "\n" + kd + "\n" + head + "\n" + line + "\n"


