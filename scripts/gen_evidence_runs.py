"""Write the run files of the KAT-dependent `#eval` evidence (Python 3, standard library only).

usage: python3 scripts/gen_evidence_runs.py <falcon512-KAT.rsp> <outdir>

<falcon512-KAT.rsp> is the Falcon-512 KAT file of the Falcon round-3 submission package (see
evidence/README.md for where to download it); its sha256 is checked first. Every file written to
<outdir> is a Lean file run with `lake env lean <file>` from the repository root after `lake build`:

  key-check-d45/{halfEven,halfUp}-0-{a,b}.lean            LIMITS E1
  key-check-d127/{halfEven,halfUp}-{0,16,32}-{a,b}.lean   LIMITS E2
  key-check-d127/decode.lean                              LIMITS E2
  key-check-d127-xn32/survey.lean                         LIMITS E3
  kat-entries/KatS0.lean ... KatS11.lean                  LIMITS E8
  vectors/d45/{e0,e70,e27}.lean, vectors/d127/{e0,e70}.lean  LIMITS E17

Each file is the KAT data (hexadecimal strings copied from the .rsp) followed by code from
evidence/ or from this script. Nothing is read from the network.
"""
import hashlib
import os
import sys

SHA = "dd75c946fdedef4ec46a2bee7e10c65c9126f1a839b9ced6921fd45f7354b5cd"
Q, N, P61 = 12289, 512, 2 ** 61 - 1
W = 88
MAXL = 1450
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
EV = os.path.join(ROOT, "evidence")


def read_template(*parts):
    with open(os.path.join(EV, *parts), encoding="utf-8") as f:
        return f.read()


def write(outdir, rel, text):
    path = os.path.join(outdir, rel)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print(rel)


# ---- key data (E1, E2, E3): `katSk`, `katPk` for all entries

def chunks(s, w):
    return [s[i:i + w] for i in range(0, len(s), w)]


def lean_str(h):
    return "String.join [\n" + ",\n".join('    "' + p + '"' for p in chunks(h, 90)) + "]"


def katdata(data, sha):
    ents, cur = [], {}
    for line in data.decode("ascii").splitlines():
        if " = " not in line:
            continue
        k, v = line.split(" = ", 1)
        if k == "count":
            cur = {"count": int(v)}
            ents.append(cur)
        elif k in ("sk", "pk"):
            if not all(c in "0123456789ABCDEFabcdef" for c in v):
                sys.exit("non-hex field")
            cur[k] = v
    if [e["count"] for e in ents] != list(range(len(ents))):
        sys.exit("count sequence")
    lines = ["-- generated by scripts/gen_evidence_runs.py from falcon512-KAT.rsp",
             "-- sha256 " + sha, "-- entries: " + str(len(ents))]
    for name in ("sk", "pk"):
        lines.append("def kat" + name.capitalize() + " : Array String := #[")
        lines.append(",\n".join("  " + lean_str(e[name]) for e in ents))
        lines.append("]")
    return "\n".join(lines) + "\n"


def key_run(imports, kd, head, line):
    return "".join("import " + m + "\n" for m in imports) + "\n" + kd + "\n" + head + "\n" + line + "\n"


SURVEY_DOC = ("/-! `checkFast` at ties to even, `xn = 32`, `δ127q` on the 100 round-3 Falcon-512 KAT\n"
              "keys (keys as in the key-check surveys). `#eval` only. -/\n")


# ---- entries (E8, E17)

def parse(text):
    ents, cur = [], {}
    for line in text.splitlines():
        line = line.strip()
        if " = " in line:
            k, v = line.split(" = ", 1)
            if k == "count" and cur:
                ents.append(cur)
                cur = {}
            cur[k] = v
    if cur:
        ents.append(cur)
    return ents


def hexlines(name, h):
    ch = [h[i:i + W] for i in range(0, len(h), W)] or [""]
    out = ["    %s := String.join [" % name]
    for j, c in enumerate(ch):
        out.append('      "%s"%s' % (c, "]" if j + 1 == len(ch) else ","))
    return out


def htp(data):
    sh = hashlib.shake_256(data).digest(8192)
    c, i = [], 0
    while len(c) < N:
        t = sh[i] * 256 + sh[i + 1]
        i += 2
        if t < 5 * Q:
            c.append(t % Q)
    return c


def fp(c):
    a = 0
    for x in reversed(c):
        a = (a * 65536 + x) % P61
    return a


def kat_entry(e):
    sm = bytes.fromhex(e["sm"])
    mlen, smlen = int(e["mlen"]), int(e["smlen"])
    msg = bytes.fromhex(e["msg"])
    assert len(sm) == smlen and len(msg) == mlen and sm[42:42 + mlen] == msg
    sl = sm[0] * 256 + sm[1]
    assert 2 + 40 + mlen + sl == smlen and sm[42 + mlen] == 0x29
    c = htp(sm[2:42] + msg)
    n = int(e["count"])
    out = ["def e%d : KatEntry where" % n, "    count := %d" % n]
    out += hexlines("msg", e["msg"]) + hexlines("pk", e["pk"]) + hexlines("sk", e["sk"])
    out += hexlines("sm", e["sm"])
    out.append("    fpC := %d" % fp(c))
    out.append("")
    return n, out


def kat_slices(ents):
    blocks = [kat_entry(e) for e in ents]
    slices, cur, curl = [], [], 0
    for b in blocks:
        if cur and curl + len(b[1]) > MAXL - 40:
            slices.append(cur)
            cur, curl = [], 0
        cur.append(b)
        curl += len(b[1])
    slices.append(cur)
    files = []
    for k, sl in enumerate(slices):
        ns = [b[0] for b in sl]
        lines = ["import FalconPrecision.Exec.CodecKat", "",
                 "/-! Entries %d-%d of the round-3 `falcon512-KAT.rsp` (sha256 `dd75c946…7354b5cd`),"
                 % (ns[0], ns[-1]),
                 "generated by `scripts/gen_evidence_runs.py`; `fpC` from Python `hashlib`. `sliceB` is",
                 "true by `#eval` (compiled code run by Lean's interpreter), not by a kernel proof. -/", "",
                 "open FalconPrecision.Exec.Codec", ""]
        for b in sl:
            lines += b[1]
        lines.append("def slice : List KatEntry := [%s]" % ", ".join("e%d" % n for n in ns))
        lines += ["", "def sliceB : Bool := slice.all entryOkB", "",
                  "theorem slice_ok (h : sliceB = true) : ∀ e ∈ slice, EntryOk e := entriesOk_of h", "",
                  "/-- info: true -/", "#guard_msgs in", "#eval sliceB", ""]
        assert len(lines) < 1500 and all(len(x) <= 100 for x in lines), k
        files.append(("kat-entries/KatS%d.lean" % k, "\n".join(lines)))
    return files


def vec_file(e, n, d127):
    if d127:
        doc = ["/-! Reference-vector run (`δ127q` set): entry %d of the round-3 `falcon512-KAT.rsp`" % n,
               "(sha256 `dd75c946…7354b5cd`), written by `scripts/gen_evidence_runs.py`. -/"]
        run = ['#eval IO.println (genVecAt δ127q "delta127q" "2^-58 at L = 8 (root), 2^-63 at L < 8" ent)']
    else:
        doc = ["/-! Reference-vector run (`δ45q` set): entry %d of the round-3 `falcon512-KAT.rsp`" % n,
               "(sha256 `dd75c946…7354b5cd`), written by `scripts/gen_evidence_runs.py`. -/"]
        run = ["#eval IO.println (genVec ent)"]
    out = ["import FalconPrecision.Exec.RefVecOut", ""] + doc + ["",
           "open FalconPrecision.Exec FalconPrecision.Exec.Codec", "",
           "def ent : KatEntry where", "    count := %d" % n]
    for k in ("msg", "pk", "sk", "sm"):
        out += hexlines(k, e[k])
    out += ["    fpC := 0", ""] + run + [""]
    for line in out:
        assert len(line) <= 100, line
    return "\n".join(out)


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    rsp, outdir = sys.argv[1], sys.argv[2]
    with open(rsp, "rb") as f:
        data = f.read()
    got = hashlib.sha256(data).hexdigest()
    if got != SHA:
        sys.exit("sha256 mismatch: got %s, expected %s" % (got, SHA))
    kd = katdata(data, got)
    imp = ["FalconPrecision.Exec.Round3Codec", "FalconPrecision.Exec.CheckFast"]
    h45 = read_template("key-check-d45", "RunHead.lean")
    h127 = read_template("key-check-d127", "RunHead.lean")
    for rm in ("halfEven", "halfUp"):
        for half, lo, hi in (("a", 0, 50), ("b", 50, 100)):
            write(outdir, "key-check-d45/%s-0-%s.lean" % (rm, half),
                  key_run(imp + ["FalconPrecision.Exec.Instance45"], kd, h45,
                          "#eval runCfg .%s 0 %d %d" % (rm, lo, hi)))
            for xn in (0, 16, 32):
                write(outdir, "key-check-d127/%s-%d-%s.lean" % (rm, xn, half),
                      key_run(imp, kd, h127, "#eval runCfg .%s %d %d %d" % (rm, xn, lo, hi)))
    write(outdir, "key-check-d127/decode.lean", key_run(imp, kd, h127, "#eval runDecode 0 100"))
    write(outdir, "key-check-d127-xn32/survey.lean",
          "".join("import " + m + "\n" for m in imp) + "\n" + SURVEY_DOC + "\n" + kd + "\n"
          + read_template("key-check-d127-xn32", "RunTail.lean"))
    ents = parse(data.decode("ascii"))   # the checked bytes, not a second read
    assert [int(e["count"]) for e in ents] == list(range(100))
    for rel, text in kat_slices(ents):
        write(outdir, rel, text)
    for n in (0, 70, 27):
        write(outdir, "vectors/d45/e%d.lean" % n, vec_file(ents[n], n, False))
    for n in (0, 70):
        write(outdir, "vectors/d127/e%d.lean" % n, vec_file(ents[n], n, True))


main()
