def nat_list(c):
    out, cur = [], "  ["
    for j, x in enumerate(c):
        t = str(x) + ("]" if j + 1 == len(c) else ",")
        if len(cur) + 1 + len(t) > 96:
            out.append(cur)
            cur = "   " + t
        else:
            cur += ("" if cur.endswith("[") else " ") + t
    out.append(cur)
    return out


